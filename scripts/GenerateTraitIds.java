import com.google.home.TraitFactory;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.HashSet;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.zip.ZipFile;

public class GenerateTraitIds {
  public static void main(String[] args) throws Exception {
    if (args.length != 2) throw new IllegalArgumentException("Expected SDK types JAR and output path");
    Map<String, String> traits = new TreeMap<>();
    Set<String> ids = new HashSet<>();
    try (ZipFile zip = new ZipFile(args[0])) {
      var entries = zip.stream().map(entry -> entry.getName())
        .filter(name -> name.matches("com/google/home/(google|matter/standard)/[^/$]+Trait\\.class"))
        .sorted().toList();
      if (entries.isEmpty()) throw new IllegalStateException("No built-in traits found");
      for (String entry : entries) {
        String trait = entry.substring(entry.lastIndexOf('/') + 1, entry.length() - 6);
        String name = entry.startsWith("com/google/home/google/") ? "Google" + trait : trait;
        String className = entry.substring(0, entry.length() - "Trait.class".length()).replace('/', '.');
        TraitFactory<?> factory = (TraitFactory<?>) Class.forName(className).getField("Companion").get(null);
        String id = factory.getFactory().getTraitId();
        if (!name.matches("[A-Za-z][A-Za-z0-9_]*") ||
            id == null || !id.matches("[A-Za-z0-9._-]+") ||
            traits.putIfAbsent(name, id) != null || !ids.add(id)) {
          throw new IllegalStateException("Invalid or duplicate trait: " + name + " = " + id);
        }
      }
    }
    StringBuilder output = new StringBuilder(
      "// Generated by scripts/GenerateTraitIds.java from the Google Home SDK.\n" +
      "// prettier-ignore\n" +
      "export const TraitIds = {\n"
    );
    traits.forEach((name, id) ->
      output.append("  ").append(name).append(": '").append(id).append("',\n"));
    output.append("} as const;\n\n")
      .append("export type TraitId = (typeof TraitIds)[keyof typeof TraitIds];\n");
    Files.writeString(Path.of(args[1]), output);
    System.out.println("Generated " + traits.size() + " trait IDs");
  }
}
